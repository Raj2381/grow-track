const started = Date.now();
const first = build();
const hash = hashOf(first.files);

if (process.argv.includes("--check")) {
  const second = build();
  const same = hash === hashOf(second.files);
  console.log(`run 1 ${hash}\nrun 2 ${hashOf(second.files)}\ndeterministic: ${same ? "YES" : "NO"}`);
  const onDisk = [...first.files.keys()].filter((f) => !existsSync(path.join(ROOT, f)) || readFileSync(path.join(ROOT, f), "utf8") !== first.files.get(f));
  console.log(onDisk.length ? `files on disk differ from a fresh build: ${onDisk.length} (run npm run generate:data)` : "files on disk match a fresh build");
  process.exit(same ? 0 : 1);
}

write(first.files);
const failed = first.report.checks.filter((c) => !c.pass);
console.log(`wrote ${first.files.size} files in ${((Date.now() - started) / 1000).toFixed(1)}s (sha256 ${hash.slice(0, 12)})`);
console.log(`checks: ${first.report.checks.length - failed.length}/${first.report.checks.length} passed`);
failed.forEach((c) => console.log(`  FAIL ${c.name}: ${c.detail}`));
process.exit(failed.length ? 1 : 0);
