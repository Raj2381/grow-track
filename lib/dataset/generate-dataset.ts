/**
 * Builds the unified synthetic dataset and writes every output.
 *
 *   npm run generate:data            write files
 *   npm run generate:data -- --check generate twice and prove the output is byte-identical
 *
 * Outputs
 *   data/students.generated.json     full records of all students (compact JSON)
 *   data/students.index.json         slim summary rows the admin pages import
 *   data/csv/*.csv                   one CSV per table, with missing values and outliers injected
 *   data/DATASET.md                  schema, leakage rules, statistics and sanity checks
 *   public/data/students/<id>.json   one file per student, fetched on demand by the student portal
 *   public/data/students-lite.json   id / name / roll number list for the student picker
 *   public/data/cohort.json          cohort benchmarks for the student portal
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { generateAllStudents } from "./generate";
import { computeOutcomes } from "./outcomes";
import {
  buildAdminIndex,
  buildCohort,
  buildTables,
  corruptTables,
  generateInterventions,
  toCsv,
  toStudentFile,
  type QualityIssue,
  type Table,
} from "./export";
import { buildReport, type Report } from "./validate";
import { DATASET_SEED, STUDENT_COUNT } from "./config";
import { TODAY } from "./calendar";

const ROOT = process.cwd();
type Files = Map<string, string>;

function build(): { files: Files; report: Report; issues: QualityIssue[]; tables: Table[] } {
  const all = generateAllStudents();
  const outcomes = all.flatMap((g) => computeOutcomes(g));
  const report = buildReport(all, outcomes);
  const interventions = generateInterventions(all);
  const students = all.map((g) => g.student);
  const cohort = buildCohort(students);

  const files: Files = new Map();
  files.set("data/students.generated.json", JSON.stringify(all.map(toStudentFile)));
  files.set("data/students.index.json", JSON.stringify(buildAdminIndex(students, cohort)));
  files.set("public/data/cohort.json", JSON.stringify(cohort));
  files.set(
    "public/data/students-lite.json",
    JSON.stringify(students.map((s) => ({ id: s.id, name: s.name, rollNo: s.rollNo, branch: s.branch }))),
  );
  for (const g of all) files.set(`public/data/students/${g.student.id}.json`, JSON.stringify(toStudentFile(g)));

  const tables = buildTables(all, outcomes, interventions);
  const issues = corruptTables(tables);
  for (const table of tables) files.set(`data/csv/${table.name}.csv`, toCsv(table));
  files.set("data/DATASET.md", renderDoc(report, issues, tables, interventions.length));
  return { files, report, issues, tables };
}

const hashOf = (files: Files) => {
  const h = createHash("sha256");
  [...files.keys()].sort().forEach((k) => h.update(k).update(files.get(k)!));
  return h.digest("hex");
};

function write(files: Files) {
  for (const dir of ["public/data/students", "data/csv"]) {
    const full = path.join(ROOT, dir);
    if (existsSync(full)) for (const f of readdirSync(full)) rmSync(path.join(full, f));
    mkdirSync(full, { recursive: true });
  }
  for (const [file, content] of files) {
    const full = path.join(ROOT, file);
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
}

