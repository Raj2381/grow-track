/**
 * Writes lib/supabase/database.types.ts from the migrations (applied to PGlite), in the shape `supabase gen types`
 * produces. The Supabase CLI needs a login, so this keeps the types reproducible offline.   npm run db:types
 */
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { createTestDb } from "./pglite";
import { root } from "./migrations";

const TS: Record<string, string> = {
  text: "string", varchar: "string", bpchar: "string", uuid: "string", date: "string", timestamptz: "string", timestamp: "string",
  int2: "number", int4: "number", int8: "number", numeric: "number", float4: "number", float8: "number", bool: "boolean", jsonb: "Json", json: "Json",
  _text: "string[]", _varchar: "string[]",
};

async function main() {
  const db = await createTestDb();
  const cols = (await db.query<{ table_name: string; column_name: string; udt_name: string; is_nullable: string; column_default: string | null }>(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default
    from information_schema.columns c join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE' order by c.table_name, c.ordinal_position`)).rows;
  const viewCols = (await db.query<{ table_name: string; column_name: string; udt_name: string; is_nullable: string; column_default: string | null }>(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default
    from information_schema.columns c join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public' and t.table_type = 'VIEW' order by c.table_name, c.ordinal_position`)).rows;
  const views = new Map<string, typeof cols>();
  for (const c of viewCols) views.set(c.table_name, [...(views.get(c.table_name) ?? []), c]);
  const tables = new Map<string, typeof cols>();
  for (const c of cols) tables.set(c.table_name, [...(tables.get(c.table_name) ?? []), c]);

  const type = (c: (typeof cols)[number]) => `${TS[c.udt_name] ?? "unknown"}${c.is_nullable === "YES" ? " | null" : ""}`;
  const block = (rows: typeof cols, kind: "Row" | "Insert" | "Update") =>
    rows.map((c) => {
      const optional = kind === "Update" || (kind === "Insert" && (c.is_nullable === "YES" || c.column_default !== null));
      return `          ${c.column_name}${optional ? "?" : ""}: ${type(c)}`;
    }).join("\n");

  const out = `// GENERATED by \`npm run db:types\` from supabase/migrations. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
${[...tables.entries()].map(([name, rows]) => `      ${name}: {
        Row: {
${block(rows, "Row")}
        };
        Insert: {
${block(rows, "Insert")}
        };
        Update: {
${block(rows, "Update")}
        };
        Relationships: [];
      };`).join("\n")}
    };
    Views: {
${[...views.entries()].map(([name, rows]) => `      ${name}: {
        Row: {
${block(rows, "Row").replace(/ \| null/g, " | null")}
        };
        Relationships: [];
      };`).join("\n") || "      [_ in never]: never"}
    };
    Functions: {
      add_student: { Args: { p_name: string; p_branch: string; p_section: string; p_semester?: number; p_email?: string; p_gender?: string; p_residence?: string }; Returns: Json };
      create_attendance_session: { Args: { p_session: Json; p_records: Json }; Returns: string };
      prediction_summary: { Args: { p_branch?: string | null; p_section?: string | null; p_mentor?: string | null }; Returns: Json };
      recommendation_summary: { Args: { p_department?: string | null }; Returns: Json };
      submit_faculty_evaluation: {
        Args: { p_subject_code: string; p_rating: number; p_clarity: number; p_punctuality: number; p_doubt_solving: number; p_engagement: number; p_title: string; p_description: string; p_experience_date: string | null; p_reference_code: string };
        Returns: string;
      };
      faculty_evaluation_summary: {
        Args: Record<PropertyKey, never>;
        Returns: { subject_code: string; faculty_name: string; responses: number; avg_rating: number; avg_clarity: number; avg_punctuality: number; avg_doubt_solving: number; avg_engagement: number }[];
      };
    };
    Enums: { [_ in never]: never };
    CompositeTypes: { [_ in never]: never };
  };
};
`;
  mkdirSync(path.join(root, "lib", "supabase"), { recursive: true });
  writeFileSync(path.join(root, "lib", "supabase", "database.types.ts"), out);
  console.log(`wrote lib/supabase/database.types.ts (${tables.size} tables)`);
}
main().catch((e) => { console.error(e); process.exit(1); });
